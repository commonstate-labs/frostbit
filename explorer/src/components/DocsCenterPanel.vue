function escapeTableCell(value: string) {
  return value.replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>')
}

function codeLanguage(label = '') {
  const normalized = label.toLowerCase()
  if (normalized.includes('json')) return 'json'
  if (normalized.includes('ini')) return 'ini'
  if (normalized.includes('typescript')) return 'typescript'
  return 'bash'
}

function docToMarkdown(doc: DocPage) {
  const lines = [`# ${doc.title}`, '', `> ${doc.summary}`, '']

  if (doc.params?.length) {
    lines.push(
      `| ${isEnglish.value ? 'Item' : '项目'} | ${isEnglish.value ? 'Value' : '说明'} |`,
      '| --- | --- |',
      ...doc.params.map(item => `| ${escapeTableCell(item.name)} | ${escapeTableCell(item.value)} |`),
      '',
    )
  }

  for (const section of doc.sections) {
    lines.push(`${'#'.repeat(section.level ?? 2)} ${section.heading}`, '')
    if (section.body) lines.push(section.body, '')
    if (section.bullets?.length) {
      lines.push(...section.bullets.map(bullet => `- ${bullet}`), '')
    }
    if (section.code) {
      lines.push(`\`\`\`${codeLanguage(section.codeLabel)}`, section.code, '```', '')
    }
  }

  return lines.join('\n')
}

const activeMarkdown = computed(() => docToMarkdown(activeDoc.value))

function hasActiveDoc(node: DocTreeNode, docId: string): boolean {
  if (node.docId === docId) return true
  return !!node.children?.some(child => hasActiveDoc(child, docId))
}

function findDocPath(nodes: DocTreeNode[], docId: string, trail: string[] = []): string[] | null {
  for (const node of nodes) {
    const nextTrail = [...trail, node.title]
    if (node.docId === docId) return nextTrail
    if (node.children) {
      const found = findDocPath(node.children, docId, nextTrail)
      if (found) return found
    }
  }
  return null
}

const visibleRows = computed<TreeRow[]>(() => {
  const rows: TreeRow[] = []
  const visit = (nodes: DocTreeNode[], depth: number) => {
    for (const node of nodes) {
      const branch = !!node.children?.length
      const expanded = expandedIds.value.has(node.id)
      rows.push({ node, depth, branch, expanded, active: hasActiveDoc(node, activeDoc.value.id) })
      if (branch && expanded && node.children) visit(node.children, depth + 1)
    }
  }
  visit(docTree.value, 0)
  return rows
})

const activePath = computed(() => findDocPath(docTree.value, activeDoc.value.id)?.join(' / ') || (isEnglish.value ? 'Documentation' : '文档中心'))

function toggleNode(node: DocTreeNode) {
  const next = new Set(expandedIds.value)
  if (next.has(node.id)) next.delete(node.id)
  else next.add(node.id)
  expandedIds.value = next
}

function selectNode(node: DocTreeNode) {
  if (node.children?.length) {
    toggleNode(node)
    return
  }
  if (node.docId) void openDoc(node.docId)
}

function rowPadding(depth: number) {
  return `${10 + depth * 18}px`
